"""Generate pythia_numbers.tex from a Pythia robust.json (zz_robust --line public) and the matching H0-bars json
(pythia_h0_bars.py).  Usage:

  python fill_pythia_numbers.py <robust.json> <h0_bars.json> [<out.tex>]

Defaults reproduce the round-4 (33-checkpoint) values; for round 5 pass the 55-checkpoint files.
"""
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
V5 = HERE.parent          # repository root (mirrors the zigzag_v5 layout)
rob_path = Path(sys.argv[1]) if len(sys.argv) > 1 else V5 / 'cloud_return_round4' / 'analysis_r4' / 'pythia_runs' / 'pythia-1.4b.robust.json'
hb_path = Path(sys.argv[2]) if len(sys.argv) > 2 else V5 / 'paper_sec4' / 'pythia_h0_bars.json'
out_path = Path(sys.argv[3]) if len(sys.argv) > 3 else HERE / 'pythia_numbers.tex'

r = json.loads(rob_path.read_text(encoding='utf8'))
hb = json.loads(hb_path.read_text(encoding='utf8'))
steps = r['steps']
assert hb['steps'] == steps


def grid_text(steps):
    """Describe the checkpoint grid in words: maximal arithmetic runs."""
    runs, i = [], 0
    while i < len(steps):
        j = i
        d = steps[i + 1] - steps[i] if i + 1 < len(steps) else None
        while d and j + 1 < len(steps) and steps[j + 1] - steps[j] == d:
            j += 1
        if j - i >= 2:
            runs.append(f"${steps[i]},\\ldots,{steps[j]}$ (every ${d}$)")
            i = j + 1
        else:
            runs.append(f"${steps[i]}$")
            i += 1
    if len(runs) > 1:
        return 'steps ' + ', '.join(runs[:-1]) + ', and ' + runs[-1]
    return 'steps ' + runs[0]


P1, P2, P4, S3 = r['P1'], r['P2'], r['P4'], r['temporal_S3']
zz_only = [d for d in hb['zigzag'] if d['finite'] and not d['in_mono']]
shared = sum(1 for d in hb['zigzag'] if d['finite'] and d['in_mono'])
merges06 = [d for d in P4['h0_merge'] if d['theta'] == 0.6 and d['support'] is not None and d['support'] >= 0.95]


def first_merge(cell):
    for d in sorted(merges06, key=lambda d: d['to_step']):
        if cell in d['added']:
            return d
    return None


m_us, m_text = first_merge('e_iso_us'), first_merge('e_iso_text')
lines = [
    f"% Generated by fill_pythia_numbers.py from {rob_path.name} ({len(steps)} checkpoints) and {hb_path.name}.",
    f"\\newcommand{{\\PyNck}}{{{len(steps)}}}",
    f"\\newcommand{{\\PyGrid}}{{{grid_text(steps)}}}",
    f"\\newcommand{{\\PyPointExits}}{{{P1['point_exits']}}}",
    f"\\newcommand{{\\PyRobustExits}}{{{len(P1['robust_exits'])}}}",
    f"\\newcommand{{\\PyZigFinite}}{{{hb['counts']['zigzag_finite']}}}",
    f"\\newcommand{{\\PyMonoFinite}}{{{hb['counts']['mono_finite']}}}",
    f"\\newcommand{{\\PyExtra}}{{{len(zz_only)}}}",
    f"\\newcommand{{\\PySupLo}}{{{min(d['support'] for d in zz_only):.2f}}}" if zz_only else "\\newcommand{\\PySupLo}{--}",
    f"\\newcommand{{\\PySupHi}}{{{max(d['support'] for d in zz_only):.2f}}}" if zz_only else "\\newcommand{\\PySupHi}{--}",
    f"\\newcommand{{\\PySthree}}{{{S3['p_lower']:.3f}}}",
    f"\\newcommand{{\\PyEobs}}{{{S3['E_obs']:.1f}}}",
    f"\\newcommand{{\\PyEnull}}{{{S3['null_median']:.1f}}}",
    f"\\newcommand{{\\PyBirthIsoUs}}{{{m_us['to_step'] if m_us else '--'}}}",
    f"\\newcommand{{\\PyBirthIsoText}}{{{m_text['to_step'] if m_text else '--'}}}",
    f"\\newcommand{{\\PyBirthIsoTextSup}}{{{m_text['support']:.2f}}}" if m_text else "\\newcommand{\\PyBirthIsoTextSup}{--}",
    f"\\newcommand{{\\PyShared}}{{{shared}}}",
]
out_path.write_text('\n'.join(lines) + '\n', encoding='utf8')
print('\n'.join(lines))
print('H_P1:', P1['H_P1'], '| robust_per_theta:', P1['robust_per_theta'], '| P2 theta 0.6:', P2['0.6'])
print('h1_decrease events:', len(P4['h1_decrease']), '| robust H0 merges at 0.6:', [(d['to_step'], d['added'], d['support']) for d in merges06])
